"""
Formatter for DeepResearch Bench output format

Expected output format:
{
    "id": "task_id",
    "prompt": "original_question",
    "article": "research_article_with_citations"
}
"""

import re
from app.common.logger_util import logger


def format_deepresearch_output(task_id, question, cosight_instance):
    """Format Co-Sight output for DeepResearch Bench evaluation

    Args:
        task_id: Task identifier
        question: Original question/prompt
        cosight_instance: CoSight instance (we need access to the plan object)

    Returns:
        Dict in DeepResearch Bench format
    """
    # Extract the actual report from the plan object
    # CoSight.execute() returns a summary, but the actual report is in plan.result
    article = extract_article_from_plan(cosight_instance)

    return {
        "id": task_id,
        "prompt": question,
        "article": article
    }


def extract_article_from_plan(cosight_instance):
    """Extract the actual research article from CoSight plan object

    The actual report generated by the LLM is stored in plan.result,
    NOT in the execute() return value (which is just a summary).

    Args:
        cosight_instance: CoSight instance with plan attribute

    Returns:
        str: The actual research report/article
    """
    try:
        # Get the actual report from the plan object
        if hasattr(cosight_instance, 'plan'):
            article = cosight_instance.plan.get_plan_result()

            if article:
                logger.info(f"✓ Extracted article from plan.result ({len(article)} chars)")
                return article
            else:
                logger.warning("⚠ plan.get_plan_result() returned empty, falling back to workspace files")
                # Fallback: try to find report files in workspace
                return extract_from_workspace(cosight_instance)
        else:
            logger.error("✗ CoSight instance has no 'plan' attribute!")
            return "[ERROR] Could not access plan object"

    except Exception as e:
        logger.error(f"✗ Error extracting article from plan: {e}")
        return f"[ERROR] Failed to extract article: {str(e)}"


def extract_from_workspace(cosight_instance):
    """Fallback: Extract report from workspace files

    If plan.result is empty, look for generated HTML/MD files in the workspace
    """
    import os
    import glob

    try:
        workspace = cosight_instance.work_space_path
        logger.info(f"Searching for report files in: {workspace}")

        # Look for HTML or MD files
        report_files = []
        for ext in ['*.html', '*.md']:
            report_files.extend(glob.glob(os.path.join(workspace, ext)))

        if report_files:
            # Use the most recently modified file
            report_file = max(report_files, key=os.path.getmtime)
            logger.info(f"Found report file: {report_file}")

            with open(report_file, 'r', encoding='utf-8') as f:
                content = f.read()
                return content
        else:
            logger.warning("No report files found in workspace")
            return "[ERROR] No report generated in workspace"

    except Exception as e:
        logger.error(f"Error extracting from workspace: {e}")
        return f"[ERROR] Workspace extraction failed: {str(e)}"


def validate_citations(article):
    """Check if article contains citations (optional quality check)

    DeepResearch Bench expects citations in the article.
    This is a simple validation to check for citation markers.

    Returns:
        bool: True if citations found
    """
    # Common citation patterns
    citation_patterns = [
        r'\[\d+\]',  # [1], [2], etc.
        r'\(\d{4}\)',  # (2024), etc.
        r'https?://',  # URLs
        r'\[.*?\]\(.*?\)',  # Markdown links
    ]

    for pattern in citation_patterns:
        if re.search(pattern, article):
            return True

    return False


def add_citation_warning(article):
    """Add a warning if no citations were detected (optional)"""
    if not validate_citations(article):
        warning = "\n\n[WARNING: No citations detected in this article. DeepResearch Bench evaluation may be affected.]\n"
        logger.warning(f"No citations detected in article")
        return article + warning
    return article
